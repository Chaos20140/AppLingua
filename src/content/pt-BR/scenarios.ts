/**
 * KI-Sprachpartner – geskriptete Offline-Dialoge (brasilianisches Portugiesisch, „você“).
 * Formelle Fassungen vermeiden „o senhor / a senhora“ in Partnerrede (Geschlecht des Nutzers unbekannt)
 * und nutzen die höfliche 3. Person ohne Pronomen – so wie im brasilianischen Service-Alltag üblich.
 * Schlüsselwörter sind normalisiert (klein, ohne Akzente/Cedille) und werden als ganze Wörter/Wortgruppen erwartet.
 * Reihenfolge der Erwartungen: spezifisch vor allgemein (erste passende gewinnt).
 */
import type { Scenario, ScriptNode } from '../types';

/** [keywords, next, reaction?] */
type Exp = [keywords: string[], next: string, reaction?: string];

/** Dialogknoten: id, Partneräußerung, Deutsch, Erwartungen, fallbackNext, Hinweis (dt.), Beispielantwort */
function n(id: string, partner: string, partnerGerman: string, expect: Exp[], fallbackNext: string, hint: string, sample: string): ScriptNode {
  return {
    id, partner, partnerGerman,
    expect: expect.map(([keywords, next, reaction]) => (reaction ? { keywords, next, reaction } : { keywords, next })),
    fallbackNext, hint, sample,
  };
}

/** Endknoten – der Partner verabschiedet sich, der Nutzer antwortet frei. */
function end(id: string, partner: string, partnerGerman: string, hint: string, sample: string): ScriptNode {
  return { id, partner, partnerGerman, expect: [], fallbackNext: id, hint, sample, end: true };
}

type Def = Omit<Scenario, 'id' | 'courseId' | 'phrases'> & { phrases: [target: string, german: string][] };

function sc(d: Def): Scenario {
  return { ...d, id: `pt.sc.${d.key}`, courseId: 'pt-BR', phrases: d.phrases.map(([target, german]) => ({ target, german })) };
}

